-- Migration 0028: JRAレース名内の旧クラス名（賞金別名称）を新クラス名（勝利数別名称）へ正規化
--
-- 背景: JRAは2019年6月1日付で条件クラスの呼称を賞金別名称から勝利数別名称へ変更した
--   （500万円以下 → 1勝クラス / 1000万円以下 → 2勝クラス / 1600万円以下 → 3勝クラス）。
--   スクレイピング元（Yahoo!スポーツ）のレースタイトルに旧称がそのまま残っているケースが
--   あり、parser側は今回のPRで新称へ正規化するよう修正済み（今後の同期分は自動的に直る）が、
--   既にDBへ取り込み済みの過去レコードは再同期されない限り直らないため、本マイグレーションで
--   一括変換する。
--   900万下は正式なクラス名称変更の対象外のため、本マイグレーションでも対象外とする
--   （ユーザー確認済み: 500万/1000万/1600万のみが対象）。
--
-- 変換対象: race_type = 'jra' かつ date_time が2019-06-01以降（名称変更前のレースは
--   当時の呼称として正しいため対象外）のレコードのうち、race_name に旧称を含むもの。
--
-- ROLLBACK: 「1000万円以下」「1000万下」のいずれから変換されたかの情報が失われるため、
--   逆変換は常に「○○万下」形式へ統一する形でのみ可能（元の表記ゆれは復元できない）。
--   下記のUPDATEを新称→旧称向けに実行すれば意味的には巻き戻せるが、表記の完全な復元は
--   保証できないため、環境への適用時は事前バックアップを取得し、必要な場合は
--   バックアップからのリストアを優先すること（README.md「破壊的マイグレーション追加時の
--   運用ルール」参照）。
--   逆変換SQL例:
--     UPDATE race
--     SET race_name = REPLACE(REPLACE(REPLACE(race_name,
--           '3勝クラス', '1600万下'),
--           '2勝クラス', '1000万下'),
--           '1勝クラス', '500万下')
--     WHERE race_type = 'jra' AND date_time >= '2019-06-01T00:00:00+09:00';

UPDATE race
SET race_name = REPLACE(
        REPLACE(
            REPLACE(
                REPLACE(
                    REPLACE(
                        REPLACE(race_name, '1600万円以下', '3勝クラス'),
                        '1600万下', '3勝クラス'
                    ),
                    '1000万円以下', '2勝クラス'
                ),
                '1000万下', '2勝クラス'
            ),
            '500万円以下', '1勝クラス'
        ),
        '500万下', '1勝クラス'
    ),
    updated_at = CURRENT_TIMESTAMP
WHERE race_type = 'jra'
  AND date_time >= '2019-06-01T00:00:00+09:00'
  AND (
    race_name LIKE '%1600万円以下%' OR race_name LIKE '%1600万下%'
    OR race_name LIKE '%1000万円以下%' OR race_name LIKE '%1000万下%'
    OR race_name LIKE '%500万円以下%' OR race_name LIKE '%500万下%'
  );
