import { describe, expect, it } from 'bun:test';

import { validateRaceName } from '../../../../../src/domain/model/valueObject/raceName';

/**
 * validateRaceNameのテスト
 *
 * ## デシジョンテーブル
 *
 * | #    | 条件                       | 入力例              | 期待結果                                       |
 * |------|----------------------------|----------------------|-------------------------------------------------|
 * | T-01 | 1文字（下限）              | "A"                  | 成功                                             |
 * | T-02 | 200文字（上限）            | "あ"×200             | 成功                                             |
 * | T-03 | 通常の中間長レース名        | "中山競馬場 春分ハンデキャップ" | 成功                                       |
 * | T-04 | 特殊文字を含むレース名      | "レース-1"           | 成功                                             |
 * | T-05 | 空文字（0文字、下限未満）  | ""                   | エラー「空文字は許可されていません」            |
 * | T-06 | 201文字（上限超過）        | "あ"×201             | エラー「レース名は200文字以下である必要があります」 |
 */
describe('validateRaceName', () => {
    describe('有効なレース名の場合、バリデーションが成功する', () => {
        it.each([
            ['[T-01] 1文字（下限）はバリデーションを通過する', 'A'],
            [
                '[T-02] 200文字（上限）はバリデーションを通過する',
                'あ'.repeat(200),
            ],
            [
                '[T-03] 通常の中間長レース名はバリデーションを通過する',
                '中山競馬場 春分ハンデキャップ',
            ],
            [
                '[T-04] 特殊文字を含むレース名はバリデーションを通過する',
                'レース-1',
            ],
        ])('%s', (_title, raceName) => {
            const result = validateRaceName(raceName);

            expect(result).toBe(raceName);
        });
    });

    describe('無効なレース名の場合、バリデーションが失敗する', () => {
        it('[T-05] 空文字（0文字、下限未満）はエラーになる', () => {
            expect(() => validateRaceName('')).toThrow(
                '空文字は許可されていません',
            );
        });

        it('[T-06] 201文字（上限超過）はエラーになる', () => {
            const raceName = 'あ'.repeat(201);

            expect(() => validateRaceName(raceName)).toThrow(
                'レース名は200文字以下である必要があります',
            );
        });
    });
});
