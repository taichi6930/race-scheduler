import { describe, expect, it } from 'bun:test';

import { validateRaceDistance } from '../../../../../src/domain/model/valueObject/raceDistance';

/**
 * RaceDistanceSchema（validateRaceDistance）のテスト
 *
 * ## デシジョンテーブル
 *
 * | #    | 条件                    | 入力例   | 期待結果                                       |
 * |------|-------------------------|----------|-------------------------------------------------|
 * | T-01 | 下限に近い正数           | 0.1      | 成功                                             |
 * | T-02 | 一般的な整数距離         | 1200     | 成功                                             |
 * | T-03 | 小数点付きの距離         | 1200.5   | 成功                                             |
 * | T-04 | 上限値（30000）          | 30000    | 成功                                             |
 * | T-05 | 0（下限以下）            | 0        | エラー「距離は0よりも大きい必要があります」      |
 * | T-06 | 負数                     | -100     | エラー「距離は0よりも大きい必要があります」      |
 * | T-07 | 上限超過（30000.1）      | 30000.1  | エラー「距離は30000以下である必要があります」    |
 */
describe('validateRaceDistance', () => {
    describe('0より大きく30000以下の場合、バリデーションが成功する', () => {
        it.each([
            ['[T-01] 0.1（下限に近い正数）はバリデーションを通過する', 0.1],
            ['[T-02] 1200（一般的な整数距離）はバリデーションを通過する', 1200],
            [
                '[T-03] 1200.5（小数点付きの距離）はバリデーションを通過する',
                1200.5,
            ],
            ['[T-04] 30000（上限）はバリデーションを通過する', 30_000],
        ])('%s', (_title, distance) => {
            const result = validateRaceDistance(distance);

            expect(result).toBe(distance);
        });
    });

    describe('0以下または30000超過の場合、バリデーションが失敗する', () => {
        it('[T-05] 0（下限以下）はエラーになる', () => {
            expect(() => validateRaceDistance(0)).toThrow(
                '距離は0よりも大きい必要があります',
            );
        });

        it('[T-06] -100（負数）はエラーになる', () => {
            expect(() => validateRaceDistance(-100)).toThrow(
                '距離は0よりも大きい必要があります',
            );
        });

        it('[T-07] 30000.1（上限超過）はエラーになる', () => {
            expect(() => validateRaceDistance(30_000.1)).toThrow(
                '距離は30000以下である必要があります',
            );
        });
    });
});
