/**
 * API通信のタイムアウト時間（ミリ秒）
 * デフォルト: 5分
 * scraping Worker の同期エンドポイント（POST /sync/place, /sync/race）や
 * calendar Worker（POST /sync）など、実際のスクレイピング・外部API呼び出しを
 * 内包する「重い」エンドポイントで使用される。処理対象日数・レース数によっては
 * 数分単位で掛かりうるため、長めのタイムアウトを維持する。
 */
export const FETCH_TIMEOUT_MS = 300_000; // 5 minutes

/**
 * 軽量なAPI通信（単純なDB読み取りのみで、スクレイピングや外部API呼び出しを
 * 挟まないエンドポイント）向けのタイムアウト時間（ミリ秒）
 * デフォルト: 30秒
 *
 * メインAPIの `/place` 取得（`fetchPlaceList`）はDBから既存データを
 * 返すだけの読み取り専用エンドポイントであり、スクレイピング系エンドポイントと
 * 同じ5分を待つ必要はない。応答が無い＝異常（ハング・ネットワーク障害）である
 * 可能性が高く、短いタイムアウトで早期に失敗を検知したほうが再試行・調査を
 * 早く始められる（PERF-080）。
 */
export const LIGHT_FETCH_TIMEOUT_MS = 30_000; // 30 seconds
